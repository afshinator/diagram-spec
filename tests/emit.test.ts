import { describe, expect, test } from "bun:test";
import { mkdirSync, rmSync } from "node:fs";
import { emit, render } from "../src/emit.ts";
import { validSpec, type Spec } from "./helpers.ts";

function twoAdapterSpec(adapter: string): Spec {
  const spec = validSpec();
  spec.renderers = { behaviour: { adapter }, deployment: { adapter } } as never;
  return spec;
}

const contentsOf = (files: { path: string; contents: string }[], suffix: string) =>
  files.filter((file) => file.path.endsWith(suffix)).map((file) => file.contents);

const mustContain = (haystack: string, needles: string[]) => {
  const missing = needles.filter((needle) => !haystack.includes(needle));
  expect(missing).toEqual([]);
};

describe("dspec emit", () => {
  const spec = validSpec();
  const loop = spec.loops[0]!;
  const needed = [
    ...spec.actors.map((actor) => actor.label),
    ...spec.messages.map((message) => message.label),
    loop.id,
    String(loop.exit),
  ];
  const legend = spec.legend.map((entry) => entry.class);

  test("svg adapter carries every actor, message, the loop with its exit, and the legend", () => {
    const result = emit(twoAdapterSpec("svg"));
    expect(result.errors).toEqual([]);
    const sequence = contentsOf(result.files, ".svg").join("\n");
    mustContain(sequence, [...needed, ...legend, "reading: top-down"]);
    expect(sequence.startsWith("<svg")).toBe(true);
  });

  test("d2 adapter carries the same facts from the same YAML", () => {
    const result = emit(twoAdapterSpec("d2"));
    expect(result.errors).toEqual([]);
    const source = contentsOf(result.files, ".d2").join("\n");
    mustContain(source, [...needed, ...legend, "generated by dspec"]);
    expect(source).toContain("shape: sequence_diagram");
  });

  test("mermaid adapter carries the same facts from the same YAML", () => {
    const result = emit(twoAdapterSpec("mermaid"));
    expect(result.errors).toEqual([]);
    const source = contentsOf(result.files, ".mmd").join("\n");
    mustContain(source, [...needed, ...legend, "generated by dspec", "sequenceDiagram"]);
    expect(source).toContain("loop ");
  });

  // §13.5 determinism
  test("re-emitting unchanged input is byte-identical", () => {
    for (const adapter of ["svg", "d2", "mermaid"]) {
      const first = emit(twoAdapterSpec(adapter));
      const second = emit(twoAdapterSpec(adapter));
      expect(JSON.stringify(first.files)).toBe(JSON.stringify(second.files));
    }
  });

  test("every generated file carries the do-not-edit header", () => {
    const result = emit(twoAdapterSpec("d2"));
    for (const file of result.files) {
      expect(file.contents).toContain("generated by dspec");
      expect(file.contents).toContain("do not edit");
    }
  });

  // §13.7 the original failure mode
  test("a components-only spec cannot render", () => {
    const broken = validSpec();
    broken.views = [{ id: "deployment", kind: "component", caption: "what runs where" }];
    broken.messages = [];
    broken.loops = [];
    broken.renderers = { deployment: { adapter: "d2" } } as never;
    const result = emit(broken);
    expect(result.files).toEqual([]);
    expect(result.errors.join("\n")).toContain("no view with kind sequence|state");
  });

  test("refuses to emit when the pairing cannot express the view", () => {
    const refused = validSpec();
    refused.renderers = { behaviour: { adapter: "svg" }, deployment: { adapter: "graphviz" } } as never;
    const result = emit(refused);
    expect(result.files).toEqual([]);
    expect(result.errors.join("\n")).toContain("graphviz");
  });

  test("carries each message in the view that declares it, not in every view", () => {
    const result = emit(twoAdapterSpec("d2"));
    const behaviour = result.files.find((file) => file.path === "behaviour.d2")?.contents ?? "";
    const deployment = result.files.find((file) => file.path === "deployment.d2")?.contents ?? "";
    // The edge, not the legend prose: messages belong to the view that declares them.
    expect(behaviour).toContain('supervisor -> dev_a: "dispatch"');
    expect(deployment).not.toContain('supervisor -> dev_a: "dispatch"');
    expect(result.files).toHaveLength(2);
  });

  test("emits exactly one loop block per behaviour view", () => {
    const d2 = emit(twoAdapterSpec("d2")).files.find((file) => file.path === "behaviour.d2")?.contents ?? "";
    expect(d2.match(/^group:/gm)).toHaveLength(1);
    const mermaid = emit(twoAdapterSpec("mermaid")).files.find((file) => file.path === "behaviour.mmd")?.contents ?? "";
    expect(mermaid.match(/^ {4}loop /gm)).toHaveLength(1);
  });

  test("turns a failing adapter into an error string, not a thrown stack", async () => {
    const outDir = new URL("../.tmp/render-error", import.meta.url).pathname;
    mkdirSync(outDir, { recursive: true });
    const broken = {
      ...twoAdapterSpec("svg"),
      renderers: { behaviour: { adapter: "broken" }, deployment: { adapter: "broken" } } as never,
    };
    // A registry whose adapter claims capability it cannot deliver at render time.
    const adapters = {
      broken: {
        id: "broken",
        capabilities: { sequence: "native" as const, state: "native" as const, component: "native" as const, deterministic: true },
        emit: (_spec: unknown, view: { id: string }) => [{ path: `${view.id}.txt`, contents: "x" }],
        render: async () => {
          throw new Error("d2 is not installed: install it or pair the view with the svg adapter");
        },
      },
    };
    const result = await render(broken, outDir, { adapters });
    expect(result.errors.join("\n")).toContain("d2 is not installed");
    expect(result.artifacts).toEqual([]);
    rmSync(outDir, { recursive: true, force: true });
  });

  // §13.6 renderer-agnosticism, proven by rendering rather than by assertion.
  // Two adapters whose output is a real artifact:
  //   d2  - emits DSL, then the installed `d2` binary (v0.9.x) renders it to SVG.
  //   svg - emits SVG directly, so its artifact needs no runtime at all.
  // mermaid is deliberately emit-only: `mmdc` fetches a browser on first run, and
  // the core must not perform a network install.
  // Environment: requires the `d2` binary on PATH. Skipped (not silently passed)
  // when absent so the requirement stays visible.
  // Labels deliberately differ from ids, so a label in the artifact can only come
  // from rendering that actor. With label === id, a loop's `over:` line would
  // satisfy the assertion even if the actor header were missing.
  function renderFixture(): Spec {
    const spec = validSpec();
    spec.actors = [
      { id: "node-1", label: "Requester node", role: "asks for work", kind: "human" },
      { id: "node-2", label: "Worker node", role: "does the work", kind: "service" },
      { id: "node-3", label: "Reviewer node", role: "accepts the result", kind: "human" },
    ];
    spec.messages = [
      { from: "node-1", to: "node-2", label: "dispatch", view: "behaviour" },
      { from: "node-2", to: "node-1", label: "report", view: "behaviour" },
      { from: "node-1", to: "node-3", label: "verdict", view: "behaviour" },
    ];
    spec.loops = [
      { id: "work-cycle", over: ["node-1", "node-2", "node-3"], exit: "the reviewer accepts", view: "behaviour" },
    ];
    spec.terminal = [{ actor: "node-1", action: "publishes the result", produces: ["plan.md"] }];
    spec.bands = [
      { id: "control", label: "control plane", membership: ["node-1"], definition: "the requester", view: "deployment" },
      { id: "workers", label: "worker plane", membership: ["node-2", "node-3"], definition: "the workers", view: "deployment" },
    ];
    return spec;
  }

  const twoRenderers = test.skipIf(!Bun.which("d2"));
  twoRenderers("two adapters render the same YAML and both artifacts carry every actor and the loop", async () => {
    const spec = renderFixture();
    const actorLabels = spec.actors.map((actor) => actor.label);
    const messageLabels = spec.messages.filter((message) => message.view === "behaviour").map((m) => m.label);
    const loop = spec.loops[0]!;
    const root = new URL("../.tmp/two-adapter", import.meta.url).pathname;
    rmSync(root, { recursive: true, force: true });

    for (const adapter of ["d2", "svg"]) {
      const outDir = `${root}/${adapter}`;
      mkdirSync(outDir, { recursive: true });
      const paired = renderFixture();
      paired.renderers = { behaviour: { adapter }, deployment: { adapter } } as never;
      const result = await render(paired, outDir);
      expect({ adapter, errors: result.errors }).toEqual({ adapter, errors: [] });

      // The behaviour artifact carries every actor, every message, and the loop with its exit.
      const behaviour = await Bun.file(`${outDir}/behaviour.svg`).text();
      mustContain(behaviour, [...actorLabels, ...messageLabels, loop.id, String(loop.exit)]);

      // The deployment artifact carries every actor.
      const deployment = await Bun.file(`${outDir}/deployment.svg`).text();
      mustContain(deployment, actorLabels);
    }

    rmSync(root, { recursive: true, force: true });
  });
});
