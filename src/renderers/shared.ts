import type { Band, DiagramContent, FlowClass, Loop, Message, View } from "../schema.ts";
import { byCodeUnit } from "../schema.ts";

/** Shared renderer vocabulary. Each adapter still owns its own syntax. */
export const GENERATED_NOTE = "generated by dspec from diagram-content.yaml — do not edit";
export const GENERATED_HEADER = `# ${GENERATED_NOTE}`;

export const bandLabel = (band: Band) =>
  `${band.label}: ${band.definition ?? "no definition"} — members: ${band.membership.join(", ")}`;

export const loopLabel = (loop: Loop) => `${loop.id} over ${loop.over.join(", ")} until ${loop.exit ?? ""}`;

export const legendText = (spec: DiagramContent) =>
  spec.legend.map((entry) => `${entry.class} = ${entry.meaning}`).join(" | ");

export const terminalText = (spec: DiagramContent) =>
  spec.terminal.map((entry) => `${entry.actor}: ${entry.action} -> ${entry.produces.join(", ")}`);

export const sourcesText = (spec: DiagramContent) => `source of truth: ${spec.meta.source_of_truth.join(", ")}`;

/** Bands that belong to this view; a band with no `view` is global. */
export const bandsFor = (spec: DiagramContent, view: View) =>
  spec.bands.filter((band) => !band.view || band.view === view.id).sort((a, b) => byCodeUnit(a.id, b.id));

/** The gate has already rejected an undeclared label, so a miss here is a bug, not data. */
export function classOf(spec: DiagramContent, label: string): FlowClass {
  const entry = spec.vocabulary.find((candidate) => candidate.label === label);
  if (!entry) throw new Error(`message label '${label}' is not in vocabulary: the gate was bypassed`);
  return entry.kind;
}

export const symmetricClass = (spec: DiagramContent, label: string) =>
  spec.vocabulary.find((candidate) => candidate.label === label)?.symmetric ?? false;

// shortcut: ids are normalised per adapter, so `a-b` and `a.b` would collide there;
// the validator rejects duplicate ids but not duplicate normalised ids. Upgrade if
// authors start using punctuation-only id differences.
export const id = (value: string) => value.replace(/[^A-Za-z0-9_]/g, "_");

export const messagesOf = (spec: DiagramContent, view: View) =>
  spec.messages.filter((message) => message.view === view.id);

export const loopsOf = (spec: DiagramContent, view: View) => spec.loops.filter((loop) => loop.view === view.id);

/**
 * Walk messages in declaration order, opening and closing a loop block around
 * each contiguous run whose endpoints are both inside a loop's `over` set.
 */
export function visitWithLoops(
  messages: Message[],
  loops: Loop[],
  handlers: { open: (loop: Loop) => void; close: () => void; message: (message: Message) => void },
) {
  const covering = (message: Message) =>
    loops.find((loop) => loop.over.includes(message.from) && loop.over.includes(message.to));
  let open: string | null = null;
  for (const message of messages) {
    const loop = covering(message);
    if (open !== null && loop?.id !== open) {
      handlers.close();
      open = null;
    }
    if (loop && open === null) {
      handlers.open(loop);
      open = loop.id;
    }
    handlers.message(message);
  }
  if (open !== null) handlers.close();
}
